-- Reconciled from the live Supabase catalog for the recorded applied migration.
create table if not exists public.parent_role_requests (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 status text not null default 'pending' check (status in ('pending','approved','rejected')),
 created_at timestamptz not null default now(),
 decided_at timestamptz,
 decided_by uuid references auth.users(id)
);
create unique index if not exists parent_role_requests_one_pending on public.parent_role_requests(user_id) where status='pending';
alter table public.parent_role_requests enable row level security;
revoke all on public.parent_role_requests from anon,authenticated;
CREATE OR REPLACE FUNCTION public.admin_decide_parent_role_request(p_request_id bigint, p_approve boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE v_uid uuid;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'admin_required';
  END IF;
  IF p_request_id IS NULL OR p_approve IS NULL THEN
    RAISE EXCEPTION 'parametres_invalides';
  END IF;

  SELECT user_id INTO v_uid
  FROM public.parent_role_requests
  WHERE id=p_request_id AND status='pending'
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'demande_indisponible'; END IF;

  IF p_approve THEN
    UPDATE public.profiles SET role='parent' WHERE id=v_uid;
    IF NOT FOUND THEN RAISE EXCEPTION 'profil_introuvable'; END IF;
  END IF;

  UPDATE public.parent_role_requests
  SET status=CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
      decided_at=now(),decided_by=auth.uid()
  WHERE id=p_request_id;

  PERFORM public.audit_log(
    CASE WHEN p_approve THEN 'role.parent.approved' ELSE 'role.parent.rejected' END,
    'parent_role_request',p_request_id::text,NULL,
    jsonb_build_object('user_id',v_uid),''
  );
  RETURN jsonb_build_object('ok',true,'status',
    CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END);
END;
$function$

CREATE OR REPLACE FUNCTION public.admin_parent_role_requests()
 RETURNS TABLE(request_id bigint, user_id uuid, pseudo text, created_at timestamp with time zone)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'admin_required';
  END IF;
  RETURN QUERY
  SELECT r.id,r.user_id,COALESCE(p.pseudo,''),r.created_at
  FROM public.parent_role_requests r
  JOIN public.profiles p ON p.id=r.user_id
  WHERE r.status='pending'
  ORDER BY r.created_at ASC;
END;
$function$

revoke all on function public.admin_decide_parent_role_request(bigint,boolean) from public, anon;
grant execute on function public.admin_decide_parent_role_request(bigint,boolean) to authenticated;
revoke all on function public.admin_parent_role_requests() from public, anon;
grant execute on function public.admin_parent_role_requests() to authenticated;
