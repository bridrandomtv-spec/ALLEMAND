CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'pg_catalog','public'
AS $$
BEGIN
  INSERT INTO public.profiles(id,pseudo,role,niveau,filiere,wilaya)
  VALUES(NEW.id,COALESCE(NEW.raw_user_meta_data->>'pseudo',''),'eleve',
    NEW.raw_user_meta_data->>'niveau',
    NEW.raw_user_meta_data->>'filiere',
    NEW.raw_user_meta_data->>'wilaya')
  ON CONFLICT(id) DO NOTHING;

  IF lower(COALESCE(NEW.raw_user_meta_data->>'requested_role',''))='parent' THEN
    INSERT INTO public.parent_role_requests(user_id,status)
    VALUES(NEW.id,'pending')
    ON CONFLICT(user_id) WHERE status='pending' DO NOTHING;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS public.parent_role_requests(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending'
    CHECK(status IN ('pending','approved','rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz,
  decided_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS parent_role_requests_one_pending
  ON public.parent_role_requests(user_id) WHERE status='pending';
ALTER TABLE public.parent_role_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.parent_role_requests FROM PUBLIC,anon,authenticated;
DROP POLICY IF EXISTS parent_role_requests_admin_read ON public.parent_role_requests;
CREATE POLICY parent_role_requests_admin_read
ON public.parent_role_requests FOR SELECT TO authenticated
USING(public.is_admin());

CREATE OR REPLACE FUNCTION public.admin_parent_role_requests()
RETURNS TABLE(request_id bigint,user_id uuid,pseudo text,created_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO 'pg_catalog','public'
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN RAISE EXCEPTION 'admin_required'; END IF;
  RETURN QUERY
  SELECT r.id,r.user_id,COALESCE(p.pseudo,''),r.created_at
  FROM public.parent_role_requests r JOIN public.profiles p ON p.id=r.user_id
  WHERE r.status='pending' ORDER BY r.created_at;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_decide_parent_role_request(p_request_id bigint,p_approve boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'pg_catalog','public'
AS $$
DECLARE v_uid uuid;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN RAISE EXCEPTION 'admin_required'; END IF;
  SELECT user_id INTO v_uid FROM public.parent_role_requests
  WHERE id=p_request_id AND status='pending' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'demande_indisponible'; END IF;
  IF p_approve THEN
    UPDATE public.profiles SET role='parent' WHERE id=v_uid;
    IF NOT FOUND THEN RAISE EXCEPTION 'profil_introuvable'; END IF;
  END IF;
  UPDATE public.parent_role_requests
  SET status=CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
      decided_at=now(),decided_by=auth.uid()
  WHERE id=p_request_id;
  PERFORM public.audit_log(
    CASE WHEN p_approve THEN 'role.parent.approved' ELSE 'role.parent.rejected' END,
    'parent_role_request',p_request_id::text,NULL,
    jsonb_build_object('user_id',v_uid),''
  );
  RETURN jsonb_build_object('ok',true,'status',
    CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END);
END;
$$;

CREATE TABLE IF NOT EXISTS public.parent_link_requests(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  child_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending'
    CHECK(status IN ('pending','accepted','rejected','cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz,
  decided_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  CONSTRAINT parent_link_requests_not_self CHECK(parent_id<>child_id)
);
CREATE INDEX IF NOT EXISTS parent_link_requests_child_pending_idx
  ON public.parent_link_requests(child_id,created_at DESC) WHERE status='pending';
CREATE INDEX IF NOT EXISTS parent_link_requests_parent_idx
  ON public.parent_link_requests(parent_id,created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS parent_link_requests_one_pending_pair
  ON public.parent_link_requests(parent_id,child_id) WHERE status='pending';
ALTER TABLE public.parent_link_requests ENABLE ROW LEVEL SECURITY;
