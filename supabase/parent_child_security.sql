CREATE OR REPLACE FUNCTION public.request_child_link(p_email text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'pg_catalog','public'
AS $$
DECLARE v_child uuid; v_role text;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'auth_required'; END IF;
  SELECT role INTO v_role FROM public.profiles WHERE id=auth.uid();
  IF v_role IS DISTINCT FROM 'parent' THEN RAISE EXCEPTION 'parent_role_required'; END IF;
  IF p_email IS NULL OR length(btrim(p_email))<5 OR length(btrim(p_email))>254
    OR position('@' IN btrim(p_email))<2 THEN RAISE EXCEPTION 'email_invalide'; END IF;
  SELECT u.id INTO v_child FROM auth.users u
  JOIN public.profiles p ON p.id=u.id
  WHERE lower(u.email)=lower(btrim(p_email)) AND p.role='eleve' AND u.id<>auth.uid()
  LIMIT 1;
  IF v_child IS NOT NULL AND NOT EXISTS(
    SELECT 1 FROM public.child_links WHERE parent_id=auth.uid() AND child_id=v_child
  ) THEN
    INSERT INTO public.parent_link_requests(parent_id,child_id,status)
    VALUES(auth.uid(),v_child,'pending')
    ON CONFLICT(parent_id,child_id) WHERE status='pending' DO NOTHING;
  END IF;
  RETURN jsonb_build_object('ok',true,'status','request_received');
END;
$$;

CREATE OR REPLACE FUNCTION public.my_parent_link_requests()
RETURNS TABLE(request_id bigint,parent_id uuid,parent_pseudo text,created_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog','public'
AS $$
  SELECT r.id,r.parent_id,COALESCE(p.pseudo,''),r.created_at
  FROM public.parent_link_requests r LEFT JOIN public.profiles p ON p.id=r.parent_id
  WHERE auth.uid() IS NOT NULL AND r.child_id=auth.uid() AND r.status='pending'
    AND EXISTS(SELECT 1 FROM public.profiles me WHERE me.id=auth.uid() AND me.role='eleve')
  ORDER BY r.created_at DESC;
$$;

CREATE OR REPLACE FUNCTION public.my_child_link_requests()
RETURNS TABLE(request_id bigint,child_id uuid,child_pseudo text,status text,created_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog','public'
AS $$
  SELECT r.id,r.child_id,COALESCE(p.pseudo,''),r.status,r.created_at
  FROM public.parent_link_requests r LEFT JOIN public.profiles p ON p.id=r.child_id
  WHERE auth.uid() IS NOT NULL AND r.parent_id=auth.uid()
    AND EXISTS(SELECT 1 FROM public.profiles me WHERE me.id=auth.uid() AND me.role='parent')
  ORDER BY r.created_at DESC LIMIT 100;
$$;

CREATE OR REPLACE FUNCTION public.respond_parent_link_request(p_request_id bigint,p_accept boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog','public'
AS $$
DECLARE v_req public.parent_link_requests%ROWTYPE; v_parent_role text; v_child_role text;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'auth_required'; END IF;
  SELECT * INTO v_req FROM public.parent_link_requests
  WHERE id=p_request_id AND child_id=auth.uid() AND status='pending' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'demande_indisponible'; END IF;
  SELECT role INTO v_parent_role FROM public.profiles WHERE id=v_req.parent_id;
  SELECT role INTO v_child_role FROM public.profiles WHERE id=auth.uid();
  IF v_parent_role IS DISTINCT FROM 'parent' OR v_child_role IS DISTINCT FROM 'eleve'
    THEN RAISE EXCEPTION 'roles_incompatibles'; END IF;
  IF p_accept THEN
    INSERT INTO public.child_links(parent_id,child_id)
    VALUES(v_req.parent_id,v_req.child_id) ON CONFLICT(parent_id,child_id) DO NOTHING;
  END IF;
  UPDATE public.parent_link_requests
  SET status=CASE WHEN p_accept THEN 'accepted' ELSE 'rejected' END,
      decided_at=now(),decided_by=auth.uid() WHERE id=v_req.id;
  RETURN jsonb_build_object('ok',true,'status',CASE WHEN p_accept THEN 'accepted' ELSE 'rejected' END);
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_parent_link_request(p_request_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog','public'
AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'auth_required'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND role='parent')
    THEN RAISE EXCEPTION 'parent_role_required'; END IF;
  UPDATE public.parent_link_requests SET status='cancelled',decided_at=now(),decided_by=auth.uid()
  WHERE id=p_request_id AND parent_id=auth.uid() AND status='pending';
  IF NOT FOUND THEN RAISE EXCEPTION 'demande_indisponible'; END IF;
  RETURN jsonb_build_object('ok',true,'status','cancelled');
END;
$$;

CREATE OR REPLACE FUNCTION public.unlink_child(p_child_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog','public'
AS $$
DECLARE v_deleted integer;
BEGIN
  IF auth.uid() IS NULL OR p_child_id IS NULL THEN RAISE EXCEPTION 'auth_required'; END IF;
  DELETE FROM public.child_links cl
  WHERE cl.child_id=p_child_id AND (
    (cl.parent_id=auth.uid() AND EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND role='parent'))
    OR (cl.child_id=auth.uid() AND EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND role='eleve'))
    OR public.is_admin()
  );
  GET DIAGNOSTICS v_deleted=ROW_COUNT;
  IF v_deleted=0 THEN RAISE EXCEPTION 'lien_introuvable_ou_non_autorise'; END IF;
  RETURN jsonb_build_object('ok',true);
END;
$$;

